-- ---------- Catálogos ----------

CREATE TABLE roles (
  id     SMALLINT PRIMARY KEY,
  nombre VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE componentes (
  id                SMALLINT PRIMARY KEY,
  codigo            VARCHAR(20)  NOT NULL UNIQUE,
  nombre            VARCHAR(50)  NOT NULL,
  umbral_precaucion NUMERIC(5,2) NOT NULL CHECK (umbral_precaucion BETWEEN 0 AND 100),
  umbral_critico    NUMERIC(5,2) NOT NULL CHECK (umbral_critico BETWEEN 0 AND 100),
  CHECK (umbral_precaucion < umbral_critico)
);

CREATE TABLE niveles_alerta (
  id     SMALLINT PRIMARY KEY,
  nombre VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE marcas (
  id     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE modelos_moto (
  id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  marca_id      BIGINT      NOT NULL REFERENCES marcas (id),
  nombre        VARCHAR(50) NOT NULL,
  cilindrada_cc SMALLINT    CHECK (cilindrada_cc > 0),
  UNIQUE (marca_id, nombre)
);

-- ---------- Personas y motos ----------

-- Compatible con la autenticación de Laravel (email, password, remember_token).
CREATE TABLE users (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rol_id            SMALLINT     NOT NULL DEFAULT 2 REFERENCES roles (id),
  nombres           VARCHAR(60)  NOT NULL,
  apellidos         VARCHAR(60)  NOT NULL,
  email             VARCHAR(150) NOT NULL UNIQUE,
  email_verified_at TIMESTAMPTZ,
  password          VARCHAR(255) NOT NULL,
  remember_token    VARCHAR(100),
  created_at        TIMESTAMPTZ,
  updated_at        TIMESTAMPTZ
);

CREATE TABLE motos (
  id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id          BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  modelo_moto_id   BIGINT      NOT NULL REFERENCES modelos_moto (id),
  placa            VARCHAR(10) NOT NULL UNIQUE,
  alias            VARCHAR(50),
  anio_fabricacion SMALLINT    CHECK (anio_fabricacion BETWEEN 1980 AND 2100),
  km_al_registrar  INTEGER     CHECK (km_al_registrar >= 0),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ
);
CREATE INDEX ix_motos_user ON motos (user_id);

-- Cada cambio de aceite o de pastillas. Al registrar la moto se crea uno por
-- componente con la fecha que da el usuario y las horas de uso estimadas desde ese cambio.
CREATE TABLE mantenimientos (
  id                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  moto_id           BIGINT       NOT NULL REFERENCES motos (id) ON DELETE CASCADE,
  componente_id     SMALLINT     NOT NULL REFERENCES componentes (id),
  fecha             DATE         NOT NULL,
  km                INTEGER      CHECK (km >= 0),
  horas_uso_previas NUMERIC(8,2) NOT NULL DEFAULT 0 CHECK (horas_uso_previas >= 0),
  notas             VARCHAR(255),
  created_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_mantenimientos_moto ON mantenimientos (moto_id, componente_id, fecha DESC);

-- ---------- Telemetría simulada y modelos ----------

-- Lecturas de una ventana de 15 minutos del nodo (simulado).
-- No guarda acumulados ni diferencias: se calculan en las vistas.
CREATE TABLE ventanas (
  id                 BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  moto_id            BIGINT       NOT NULL REFERENCES motos (id) ON DELETE CASCADE,
  inicio             TIMESTAMPTZ  NOT NULL,
  temp_aceite_media  NUMERIC(5,2) NOT NULL,
  temp_aceite_max    NUMERIC(5,2) NOT NULL,
  temp_aceite_p95    NUMERIC(5,2) NOT NULL,
  temp_cabeza_media  NUMERIC(5,2) NOT NULL,
  vib_rms_rel        NUMERIC(6,3) NOT NULL CHECK (vib_rms_rel >= 0),
  arranque_frio      BOOLEAN      NOT NULL DEFAULT FALSE,
  n_frenadas         SMALLINT     NOT NULL DEFAULT 0 CHECK (n_frenadas >= 0),
  n_frenadas_bruscas SMALLINT     NOT NULL DEFAULT 0 CHECK (n_frenadas_bruscas >= 0),
  decel_sum_g        NUMERIC(8,3) NOT NULL DEFAULT 0 CHECK (decel_sum_g >= 0),
  min_sobre_umbral   NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (min_sobre_umbral BETWEEN 0 AND 15),
  created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
  UNIQUE (moto_id, inicio),
  CHECK (n_frenadas_bruscas <= n_frenadas)
);

CREATE TABLE modelos_ml (
  id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  componente_id SMALLINT     NOT NULL REFERENCES componentes (id),
  version       VARCHAR(10)  NOT NULL,
  algoritmo     VARCHAR(60)  NOT NULL,
  rmse          NUMERIC(6,2),
  mae           NUMERIC(6,2),
  entrenado_el  DATE         NOT NULL,
  UNIQUE (componente_id, version)
);

CREATE TABLE predicciones (
  id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ventana_id    BIGINT       NOT NULL REFERENCES ventanas (id) ON DELETE CASCADE,
  modelo_ml_id  BIGINT       NOT NULL REFERENCES modelos_ml (id),
  desgaste_pct  NUMERIC(5,2) NOT NULL CHECK (desgaste_pct BETWEEN 0 AND 100),
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  UNIQUE (ventana_id, modelo_ml_id)
);

-- Una alerta es el evento de cruzar un umbral. Queda atendida cuando se
-- le asigna el mantenimiento que la resolvió.
CREATE TABLE alertas (
  id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  prediccion_id    BIGINT      NOT NULL UNIQUE REFERENCES predicciones (id) ON DELETE CASCADE,
  mantenimiento_id BIGINT      REFERENCES mantenimientos (id) ON DELETE SET NULL,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_alertas_abiertas ON alertas (prediccion_id) WHERE mantenimiento_id IS NULL;

-- ---------- Vistas (datos calculados) ----------

-- Predicción con su componente, moto y nivel según los umbrales del componente.
CREATE VIEW v_predicciones AS
SELECT p.id,
       v.moto_id,
       v.inicio,
       c.codigo AS componente,
       p.desgaste_pct,
       n.id     AS nivel_id,
       n.nombre AS nivel,
       m.version AS modelo_version
FROM predicciones p
JOIN ventanas    v ON v.id = p.ventana_id
JOIN modelos_ml  m ON m.id = p.modelo_ml_id
JOIN componentes c ON c.id = m.componente_id
JOIN niveles_alerta n ON n.id = CASE
       WHEN p.desgaste_pct >  c.umbral_critico    THEN 2
       WHEN p.desgaste_pct >= c.umbral_precaucion THEN 1
       ELSE 0 END;

CREATE VIEW v_alertas AS
SELECT a.id,
       vp.moto_id,
       vp.componente,
       vp.nivel,
       vp.desgaste_pct,
       a.created_at,
       CASE WHEN a.mantenimiento_id IS NULL THEN 'abierta' ELSE 'atendida' END AS estado,
       ma.fecha AS atendida_el
FROM alertas a
JOIN v_predicciones vp ON vp.id = a.prediccion_id
LEFT JOIN mantenimientos ma ON ma.id = a.mantenimiento_id;

-- Uso acumulado desde el último cambio de cada componente. Cuenta las ventanas
-- simuladas después de que el cambio se registró en el sistema.
-- Es exactamente lo que recibe la ruta /simulate de la API de desgaste.
CREATE VIEW v_acumulados AS
WITH ultimo AS (
  SELECT DISTINCT ON (ma.moto_id, c.codigo)
         ma.moto_id, c.codigo, ma.created_at, ma.horas_uso_previas
  FROM mantenimientos ma
  JOIN componentes c ON c.id = ma.componente_id
  ORDER BY ma.moto_id, c.codigo, ma.created_at DESC, ma.id DESC
)
SELECT mo.id AS moto_id,
       COALESCE(ua.horas_uso_previas, 0) + 0.25 * COALESCE(a.ventanas, 0) AS h_desde_cambio_aceite,
       COALESCE(a.arranques_frio, 0)                                     AS arranques_frio_desde_cambio,
       COALESCE(a.temp_media, 0)                                         AS temp_aceite_media_desde_cambio,
       COALESCE(a.min_sobre_umbral, 0)                                   AS min_sobre_umbral_aceite,
       COALESCE(up.horas_uso_previas, 0) + 0.25 * COALESCE(p.ventanas, 0) AS h_desde_cambio_pastillas,
       COALESCE(p.decel, 0)                                              AS decel_acum_pastillas,
       COALESCE(p.bruscas, 0)                                            AS n_bruscas_acum_pastillas,
       COALESCE(p.frenadas, 0)                                           AS n_frenadas_acum_pastillas
FROM motos mo
LEFT JOIN ultimo ua ON ua.moto_id = mo.id AND ua.codigo = 'aceite'
LEFT JOIN ultimo up ON up.moto_id = mo.id AND up.codigo = 'pastillas'
LEFT JOIN LATERAL (
  SELECT count(*)                            AS ventanas,
         count(*) FILTER (WHERE arranque_frio) AS arranques_frio,
         round(avg(temp_aceite_media), 2)    AS temp_media,
         sum(min_sobre_umbral)               AS min_sobre_umbral
  FROM ventanas
  WHERE moto_id = mo.id AND inicio >= COALESCE(ua.created_at, '-infinity')
) a ON TRUE
LEFT JOIN LATERAL (
  SELECT count(*)                AS ventanas,
         sum(decel_sum_g)        AS decel,
         sum(n_frenadas_bruscas) AS bruscas,
         sum(n_frenadas)         AS frenadas
  FROM ventanas
  WHERE moto_id = mo.id AND inicio >= COALESCE(up.created_at, '-infinity')
) p ON TRUE;

